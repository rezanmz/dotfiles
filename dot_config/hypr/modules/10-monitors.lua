-- Monitors: Dell U3225QE (this desk's panel) plus a second 2K display.
--
-- Rules are applied in order and the LAST match wins, so:
--   1. the generic rule below gives any unknown output a sane mode
--   2. the explicit desc: rule pins this desk's panel
--   3. ~/.config/hypr/monitors.lua, if present, overrides both
--
-- This desk's panel is addressed by description ("desc:" + its EDID
-- make/model/serial), not by connector name. A description selector follows
-- the physical panel to any socket it is plugged into, so moving the U3225QE
-- between HDMI and DisplayPort needs no edit here, and the rule can never
-- accidentally match the other monitor.
--
-- monitors.lua is generated by nwg-displays (SUPER+SHIFT+D). That tool is the
-- supported way to change scale, position or alignment — hand-editing this file
-- and then using the GUI would otherwise silently disagree.
-- The GUI has a "use description instead of output name" option; with it on,
-- the GUI also writes desc: selectors and agrees with this file.

local configDir = (os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")) .. "/hypr"

-- 1. Fallback for a display we have not configured explicitly.
hl.monitor({
    output   = "",
    mode     = "preferred",
    position = "auto",
    scale    = "auto",
})

-- 2. This desk's panel: Dell UltraSharp U3225QE, 31.5" 4K at 120 Hz.
--
--    Selected by "desc:" rather than by connector name. The description is
--    EDID-derived (make + model + serial), so the rule follows the panel to
--    whichever socket it is plugged into. That is what lets the U3225QE move
--    from HDMI-A-1 to DP-1 without editing this file, and it also keeps the
--    rule from ever matching the other 2K monitor on HDMI.
--    The selector is a case-sensitive PREFIX of the description, so it must
--    match the leading characters exactly.
--
--    The link is HDMI 2.1 FRL today (1188 MHz pixel clock at 3840x2160@120),
--    so the full 4K120 mode is already running -- nothing is being throttled.
--    Scale 1.5 gives a 2560x1440 logical desktop (~93 effective PPI).
--    10-bit + EDID wide gamut use the same FRL link; the panel's HDMI Forum
--    block declares DC_36bit and BT2020RGB, and no underruns were observed
--    while 10-bit was active.
--    vrr = 1 keeps adaptive sync armed so it engages on its own once the
--    kernel exposes vrr_capable on this connector.
--
--    VRR STATUS (2026-10-19): over HDMI the panel advertises "VRRmin: 48 Hz,
--    VRRmax: 120 Hz" in its HDMI Forum VSDB, and the OSD confirms
--    "HDMI 2.1 FRL6(VRR)" -- but the running kernel reports the connector
--    property vrr_capable = 0, so Hyprland cannot turn adaptive sync on.
--    That parsing gap (HDMI Forum VRR, which the panel uses, versus AMD's
--    proprietary FreeSync VSDB) is fixed upstream in Linux 7.4, alongside
--    HDMI 2.1 VRR support proper. Whether the panel exposes an AMD FreeSync
--    VSDB over DisplayPort -- and therefore whether VRR works there on this
--    kernel -- is UNVERIFIED: DP-1 has never been connected, so no DP EDID
--    has ever been read. It has to be checked after plugging the cable in.
hl.monitor({
    output   = "desc:Dell Inc. DELL U3225QE 3Y4F584",
    mode     = "3840x2160@120",
    position = "0x0",
    scale    = 1.5,
    bitdepth = 10,
    cm       = "edid",
    vrr      = 1,
})

-- 3. GUI overrides. Absent file is not an error: a fresh machine has none.
--    hl.monitor() MERGES into the existing rule for the same output and the
--    last call wins per field, so this file owns scale/position/mode.
local override = configDir .. "/monitors.lua"
local chunk = loadfile(override)
if chunk then
    chunk()
end

-- 4. Re-arm VRR after the GUI override.
--    nwg-displays writes "vrr = 0/1" unconditionally, mirroring the kernel's
--    reported adaptive-sync state. Since the kernel cannot expose vrr_capable
--    on the HDMI connector yet, the GUI would keep writing vrr = 0 and the
--    panel would stay locked to a fixed 120 Hz forever -- even after a kernel
--    upgrade makes VRR possible.
--    This rule touches ONLY vrr, so the GUI keeps full ownership of geometry.
--    Same desc: selector, so it follows the panel across connectors.
hl.monitor({
    output = "desc:Dell Inc. DELL U3225QE 3Y4F584",
    vrr    = 1,
})
