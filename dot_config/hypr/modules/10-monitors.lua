-- Monitors: Dell U3225QE (4K, this desk's main panel) and Dell SE2723DS (2K).
--
-- Rules are applied in order and the LAST match wins, so:
--   1. the generic rule below gives any unknown output a sane mode
--   2. the explicit desc: rules pin both panels
--   3. ~/.config/hypr/monitors.lua, if present, overrides both
--
-- Both panels are addressed by description ("desc:" + their EDID
-- make/model/serial), not by connector name. A description selector follows
-- the physical panel to any socket it is plugged into, so moving a panel
-- between HDMI and DisplayPort needs no edit here.
--
-- CAUTION: a description selector identifies a PANEL, not a socket. If the
-- same physical panel is reachable through two connectors at once (for
-- example daisy-chained over the U3225QE's DP-out while also plugged into
-- the board), BOTH connectors carry the same description and one rule will
-- apply to both. Only one connector may drive a given panel at a time.
--
-- CURRENT WIRING (2026-10-19):
--   U3225QE  -> board DisplayPort, physical port DP-1, 4K120, VRR on
--   SE2723DS  -> board HDMI (HDMI-A-1), 2560x1440@75, VRR on
-- The U3225QE's DP-OUT MST mode must stay OFF in the monitor's OSD, or the
-- panel drops to an MST branch (DP-2) where 4K120 is not offered at all.
-- Turning MST off costs the U3225QE's ability to daisy-chain a second panel
-- off its DP-out; with it on, the same setup runs the 4K panel at 4K60 and
-- loses VRR on it.
--
-- monitors.lua is generated by nwg-displays (SUPER+SHIFT+D). That tool is the
-- supported way to change scale, position or alignment — hand-editing this file
-- and then using the GUI would otherwise silently disagree.
-- The GUI has a "use description instead of output name" option; with it on,
-- the GUI also writes desc: selectors and agrees with this file.

local configDir = (os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")) .. "/hypr"

-- 1. Fallback for a display we have not configured explicitly.
hl.monitor({
    output   = "",
    mode     = "preferred",
    position = "auto",
    scale    = "auto",
})

-- 2. This desk's panel: Dell UltraSharp U3225QE, 31.5" 4K at 120 Hz.
--
--    Selected by "desc:" rather than by connector name. The description is
--    EDID-derived (make + model + serial), so the rule follows the panel to
--    whichever socket it is plugged into. The selector is a case-sensitive
--    PREFIX of the description, so it must match the leading characters
--    exactly.
--
--    REFRESH RATE: 3840x2160@120 (1188 MHz pixel clock) over DisplayPort.
--
--    Getting 4K120 over DP requires the panel's DP-OUT MST mode to be OFF in
--    the monitor's OSD. With MST on, the GPU's DP port is split into MST
--    branches and the U3225QE appears as "DP-2" instead of "DP-1"; on that
--    branch the driver offered no 4K120 mode at all (modetest found 0, top
--    mode 4K60 at 594 MHz). With MST off the panel sits on the physical port
--    DP-1, and the driver offers both the 1188 MHz (CTA) and the 1097.75 MHz
--    (DisplayID reduced blanking) 4K120 timings.
--
--    This is NOT a DSC story: no dp_dsc atomic properties are exposed on any
--    connector and there is no dcn31_dsc_funcs, yet 4K120 runs at 1188 MHz
--    with 10-bit (XRGB2101010) and no link underruns. Note 1188 MHz x 30 bpp
--    is 35.6 Gbps, well past DP 1.4 HBR3 x4 (25.92 Gbps usable), so this
--    port is not limited to DP 1.4 rates. The cable was never the
--    constraint -- the MST setting was.
--
--    Scale 1.5 gives a 2560x1440 logical desktop (~93 effective PPI).
--
--    COLOR MANAGEMENT: cm = "srgb", NOT "edid"/"wide". 10-bit is unaffected
--    (still XRGB2101010; the panel's DP EDID advertises DC_36bit and
--    BT2020RGB, and no underruns were seen while 10-bit was active), but the
--    wide-gamut descriptions darken every SDR pixel. With cm = edid Hyprland
--    maps SDR against sdrMaxLuminance = 80 nits, and an sRGB page measured
--    through grim renders white 186 / 50% grey 117 instead of 255 / 127;
--    the factor is also state-dependent (same white patch: 186 in a window,
--    231 fullscreen), so screen brightness jumped when a video went
--    fullscreen. Only color-managed clients are hit -- Chrome negotiates
--    wp_color_manager_v1, kitty does not and still rendered 255 -- which is
--    why browser content looked dim while terminals looked right.
--    cm = srgb was exactly neutral in both states (255 / 127, windowed and
--    fullscreen), and cm is a panel property, not a port one: the desc:
--    selector carries it to whichever socket the U3225QE is plugged into.
--
--    VRR: on the physical port the connector exposes vrr_capable = 1 and
--    adaptive sync is active. (Over HDMI it was 0 -- HDMI Forum VRR is only
--    parsed upstream in Linux 7.4 -- and on an MST branch the property is
--    not exposed at all.) vrr = 1 keeps it armed either way.
hl.monitor({
    output   = "desc:Dell Inc. DELL U3225QE 3Y4F584",
    mode     = "3840x2160@120",
    position = "0x0",
    scale    = 1.5,
    bitdepth = 10,
    cm       = "srgb",
    vrr      = 1,
})

-- 2b. The second display: Dell SE2723DS, 27" 2K, native max 75 Hz.
--     It carries an AMD FreeSync VSDB (48-75 Hz), which is the block the
--     current kernel CAN parse -- so this panel gets real VRR, but only when
--     it sits on a DIRECT connector (the board's HDMI or DP). While it was
--     daisy-chained off the U3225QE's DP-out it was an MST branch, the
--     driver exposed no vrr_capable property there, and VRR stayed off.
--     On the board's HDMI it now reports vrr_capable = 1 and adaptive sync
--     is genuinely active (verified: the compositor's frame-callback
--     intervals vary between ~13 and ~40 ms instead of being pinned).
--     Keep it to the right of the 4K panel.
hl.monitor({
    output   = "desc:Dell Inc. DELL SE2723DS 5P097V3",
    mode     = "2560x1440@75",
    position = "2560x0",
    scale    = 1.0,
    vrr      = 1,
})

-- 3. GUI overrides. Absent file is not an error: a fresh machine has none.
--    hl.monitor() MERGES into the existing rule for the same output and the
--    last call wins per field, so this file owns scale/position/mode.
--
--    The override is loaded through a PROXY for `hl`, so that the vrr field
--    can be taken out of it. nwg-displays writes "vrr = 0/1" unconditionally,
--    mirroring the kernel's reported adaptive-sync state at the moment the GUI
--    was used. That state changes with the cabling, so the GUI's cached value
--    goes stale: while the SE2723DS was on an MST branch the GUI recorded
--    vrr = 0, and it would keep writing that even after the panel moved to
--    the board's HDMI and VRR became possible. The GUI also has no way to
--    know that a panel it has never seen supports VRR at all.
--
--    Dropping the field here rather than re-arming it afterwards means the
--    policy below is the only thing that decides VRR, and it does not depend
--    on the order the rules happen to be applied in. The GUI keeps full
--    ownership of geometry, which is what it is actually for.
local override = configDir .. "/monitors.lua"

-- The panels whose vrr this config owns, and the value it wants for them.
-- Keyed by the same desc: selectors used above, so the policy follows the
-- panels across connectors.
local VRR_POLICY = {
    ["desc:Dell Inc. DELL U3225QE 3Y4F584"] = 1,
    ["desc:Dell Inc. DELL SE2723DS 5P097V3"] = 1,
}

-- Does this output name one of our panels? The override may name a panel by
-- its full description with the connector in brackets, so the match is on the
-- panel identity, not on the whole string.
local function vrrFor(output)
    -- The panel identity, without the "desc:" prefix and without the
    -- connector the GUI may append. Both sides are reduced the same way, so
    -- the override's "desc:Dell Inc. DELL U3225QE 3Y4F584 (DP-1)" matches
    -- the policy entry for that panel.
    local function identity(s)
        if s:sub(1, 5) == "desc:" then
            s = s:sub(6)
        end
        -- The GUI appends the connector in brackets; drop it.
        local bracket = s:find("%s*%b()%s*$")
        if bracket then
            s = s:sub(1, bracket - 1)
        end
        return s
    end

    local wanted = identity(output)

    for desc, value in pairs(VRR_POLICY) do
        local panel = identity(desc)
        -- Exact match on the panel identity. The identity ends with the
        -- serial, so a plain prefix test would also match a different panel
        -- whose serial merely starts the same way.
        if wanted == panel then
            return value
        end
    end

    return nil
end

if loadfile(override) then
    -- The override runs with its own environment, in which `hl` is a proxy
    -- for the real one: hl.monitor() is the real function with the vrr field
    -- filtered out for the panels we own, and everything else is forwarded
    -- untouched.
    local proxy = {}

    for key, value in pairs(hl) do
        proxy[key] = value
    end

    proxy.monitor = function(spec)
        if type(spec) ~= "table" then
            return hl.monitor(spec)
        end

        local output = spec.output
        local want = type(output) == "string" and vrrFor(output) or nil

        if want == nil then
            -- Not a panel we own: pass it through untouched.
            return hl.monitor(spec)
        end

        -- A panel we own: drop the GUI's vrr and cm so our policy stands.
        -- vrr: the panel rules above own it -- the GUI mirrors whatever the
        -- kernel reported when it was open, which goes stale with the cabling.
        -- cm: same reasoning. The GUI writes back the preset the compositor
        -- happened to run with, so a single nwg-displays session pins the
        -- panel to a wide-gamut/HDR description and darkens every SDR pixel
        -- (see the U3225QE rule: white 186 instead of 255). Color management
        -- is a panel decision, so it lives in the rules above.
        local filtered = {}
        for key, value in pairs(spec) do
            if key ~= "vrr" and key ~= "cm" then
                filtered[key] = value
            end
        end

        return hl.monitor(filtered)
    end

    local env = setmetatable({ hl = proxy }, { __index = _G })
    local chunk = loadfile(override, "t", env)
    if chunk then
        chunk()
    end
end

-- 4. The VRR policy itself.
--
-- Both panels carry a VRR-capable mode on a direct connector: the U3225QE
-- over DisplayPort, the SE2723DS over HDMI with its FreeSync VSDB block,
-- which is the one the current kernel can parse. The rules below are the only
-- thing that turns adaptive sync on for them.
--
-- The global fallback stays off (40-look.lua: misc.vrr = 0), so a panel that
-- is not listed here gets no adaptive sync rather than an unverified one.
hl.monitor({
    output = "desc:Dell Inc. DELL U3225QE 3Y4F584",
    vrr    = 1,
})

hl.monitor({
    output = "desc:Dell Inc. DELL SE2723DS 5P097V3",
    vrr    = 1,
})
