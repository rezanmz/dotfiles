-- Monitors: Dell U3225QE (4K, this desk's main panel) and Dell SE2723DS (2K).
--
-- Rules are applied in order and the LAST match wins, so:
--   1. the generic rule below gives any unknown output a sane mode
--   2. the explicit desc: rules pin both panels
--   3. ~/.config/hypr/monitors.lua, if present, overrides both
--
-- Both panels are addressed by description ("desc:" + their EDID
-- make/model/serial), not by connector name. A description selector follows
-- the physical panel to any socket it is plugged into, so moving a panel
-- between HDMI and DisplayPort needs no edit here.
--
-- CAUTION: a description selector identifies a PANEL, not a socket. If the
-- same physical panel is reachable through two connectors at once (for
-- example daisy-chained over the U3225QE's DP-out while also plugged into
-- the board), BOTH connectors carry the same description and one rule will
-- apply to both. Only one connector may drive a given panel at a time.
--
-- monitors.lua is generated by nwg-displays (SUPER+SHIFT+D). That tool is the
-- supported way to change scale, position or alignment — hand-editing this file
-- and then using the GUI would otherwise silently disagree.
-- The GUI has a "use description instead of output name" option; with it on,
-- the GUI also writes desc: selectors and agrees with this file.

local configDir = (os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")) .. "/hypr"

-- 1. Fallback for a display we have not configured explicitly.
hl.monitor({
    output   = "",
    mode     = "preferred",
    position = "auto",
    scale    = "auto",
})

-- 2. This desk's panel: Dell UltraSharp U3225QE, 31.5" 4K at 120 Hz.
--
--    Selected by "desc:" rather than by connector name. The description is
--    EDID-derived (make + model + serial), so the rule follows the panel to
--    whichever socket it is plugged into. The selector is a case-sensitive
--    PREFIX of the description, so it must match the leading characters
--    exactly.
--
--    REFRESH RATE: the panel does 4K120 over HDMI 2.1 FRL (1188 MHz pixel
--    clock), but over DisplayPort it can only do 4K60. That is a link-bandwidth
--    limit, not a setting:
--      * 4K120 needs 1188 MHz x 24 bpp = 28.5 Gbps, and even the reduced
--        blanking timing (1097.75 MHz) needs 26.3 Gbps, which exceeds what
--        DP 1.4 HBR3 x4 can carry (25.92 Gbps usable).
--      * 4K120 over DP therefore requires DSC, and this GPU (Radeon 610M,
--        DCN 3.1) has no DSC encoder -- the kernel exposes no dp_dsc atomic
--        properties at all, and there is no dcn31_dsc_funcs.
--    So over DP the panel runs 3840x2160@60, and "3840x2160@120" in the mode
--    field silently falls back to 60. Ask for 120 here and Hyprland will not
--    complain; it just applies the closest mode the link supports.
--    Scale 1.5 gives a 2560x1440 logical desktop (~93 effective PPI).
--    10-bit + EDID wide gamut still work over DP (the panel's DP EDID
--    advertises DC_36bit and BT2020RGB); no link underruns were seen.
--
--    VRR: over HDMI the panel advertises "VRRmin: 48 Hz, VRRmax: 120 Hz" in
--    its HDMI Forum VSDB, and the OSD confirms "HDMI 2.1 FRL6(VRR)" -- but
--    the running kernel reports vrr_capable = 0 on that connector, because
--    HDMI Forum VRR (versus AMD's proprietary FreeSync VSDB) is only parsed
--    upstream in Linux 7.4.
--    Over DisplayPort the same panel advertises NO FreeSync block whatsoever
--    (its DP EDID has only base + CTA-861 + DisplayID), so there is nothing
--    for the kernel to find either way. vrr = 1 is kept armed so adaptive
--    sync engages on its own once a kernel exposes it.
hl.monitor({
    output   = "desc:Dell Inc. DELL U3225QE 3Y4F584",
    mode     = "3840x2160@60",
    position = "0x0",
    scale    = 1.5,
    bitdepth = 10,
    cm       = "edid",
    vrr      = 1,
})

-- 2b. The second display: Dell SE2723DS, 27" 2K, native max 75 Hz.
--     It carries an AMD FreeSync VSDB (48-75 Hz) over DisplayPort, which is
--     the block the current kernel CAN parse -- but only on a direct
--     (non-MST) connector. On an MST branch the driver does not expose
--     vrr_capable at all, so VRR stays off while it is daisy-chained.
--     Keep it to the right of the 4K panel.
hl.monitor({
    output   = "desc:Dell Inc. DELL SE2723DS 5P097V3",
    mode     = "2560x1440@75",
    position = "2560x0",
    scale    = 1.0,
    vrr      = 1,
})

-- 3. GUI overrides. Absent file is not an error: a fresh machine has none.
--    hl.monitor() MERGES into the existing rule for the same output and the
--    last call wins per field, so this file owns scale/position/mode.
local override = configDir .. "/monitors.lua"
local chunk = loadfile(override)
if chunk then
    chunk()
end

-- 4. Re-arm VRR after the GUI override.
--    nwg-displays writes "vrr = 0/1" unconditionally, mirroring the kernel's
--    reported adaptive-sync state. Since the kernel does not expose
--    vrr_capable on either connector yet, the GUI would keep writing vrr = 0
--    and both panels would stay locked to fixed refresh rates forever -- even
--    after a kernel upgrade makes VRR possible.
--    These rules touch ONLY vrr, so the GUI keeps full ownership of geometry.
--    Same desc: selectors, so they follow the panels across connectors.
hl.monitor({
    output = "desc:Dell Inc. DELL U3225QE 3Y4F584",
    vrr    = 1,
})

hl.monitor({
    output = "desc:Dell Inc. DELL SE2723DS 5P097V3",
    vrr    = 1,
})
