-- Monitors: Dell U3225QE (4K, this desk's main panel) and Dell SE2723DS (2K).
--
-- Rules are applied in order and the LAST match wins, so:
--   1. the generic rule below gives any unknown output a sane mode
--   2. the explicit desc: rules pin both panels
--   3. ~/.config/hypr/monitors.lua, if present, overrides both
--
-- Both panels are addressed by description ("desc:" + their EDID
-- make/model/serial), not by connector name. A description selector follows
-- the physical panel to any socket it is plugged into, so moving a panel
-- between HDMI and DisplayPort needs no edit here.
--
-- CAUTION: a description selector identifies a PANEL, not a socket. If the
-- same physical panel is reachable through two connectors at once (for
-- example daisy-chained over the U3225QE's DP-out while also plugged into
-- the board), BOTH connectors carry the same description and one rule will
-- apply to both. Only one connector may drive a given panel at a time.
--
-- CURRENT WIRING (2026-10-19):
--   U3225QE  -> board DisplayPort, physical port DP-1, 4K120, VRR on
--   SE2723DS  -> board HDMI (HDMI-A-1), 2560x1440@75, VRR on
-- The U3225QE's DP-OUT MST mode must stay OFF in the monitor's OSD, or the
-- panel drops to an MST branch (DP-2) where 4K120 is not offered at all.
-- Turning MST off costs the U3225QE's ability to daisy-chain a second panel
-- off its DP-out; with it on, the same setup runs the 4K panel at 4K60 and
-- loses VRR on it.
--
-- monitors.lua is generated by nwg-displays (SUPER+SHIFT+D). That tool is the
-- supported way to change scale, position or alignment — hand-editing this file
-- and then using the GUI would otherwise silently disagree.
-- The GUI has a "use description instead of output name" option; with it on,
-- the GUI also writes desc: selectors and agrees with this file.

local configDir = (os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")) .. "/hypr"

-- 1. Fallback for a display we have not configured explicitly.
hl.monitor({
    output   = "",
    mode     = "preferred",
    position = "auto",
    scale    = "auto",
})

-- 2. This desk's panel: Dell UltraSharp U3225QE, 31.5" 4K at 120 Hz.
--
--    Selected by "desc:" rather than by connector name. The description is
--    EDID-derived (make + model + serial), so the rule follows the panel to
--    whichever socket it is plugged into. The selector is a case-sensitive
--    PREFIX of the description, so it must match the leading characters
--    exactly.
--
--    REFRESH RATE: 3840x2160@120 (1188 MHz pixel clock) over DisplayPort.
--
--    Getting 4K120 over DP requires the panel's DP-OUT MST mode to be OFF in
--    the monitor's OSD. With MST on, the GPU's DP port is split into MST
--    branches and the U3225QE appears as "DP-2" instead of "DP-1"; on that
--    branch the driver offered no 4K120 mode at all (modetest found 0, top
--    mode 4K60 at 594 MHz). With MST off the panel sits on the physical port
--    DP-1, and the driver offers both the 1188 MHz (CTA) and the 1097.75 MHz
--    (DisplayID reduced blanking) 4K120 timings.
--
--    This is NOT a DSC story: no dp_dsc atomic properties are exposed on any
--    connector and there is no dcn31_dsc_funcs, yet 4K120 runs at 1188 MHz
--    with 10-bit (XRGB2101010) and no link underruns. Note 1188 MHz x 30 bpp
--    is 35.6 Gbps, well past DP 1.4 HBR3 x4 (25.92 Gbps usable), so this
--    port is not limited to DP 1.4 rates. The cable was never the
--    constraint -- the MST setting was.
--
--    Scale 1.5 gives a 2560x1440 logical desktop (~93 effective PPI).
--    10-bit + EDID wide gamut work over DP (the panel's DP EDID advertises
--    DC_36bit and BT2020RGB); no underruns were seen while 10-bit was active.
--
--    VRR: on the physical port the connector exposes vrr_capable = 1 and
--    adaptive sync is active. (Over HDMI it was 0 -- HDMI Forum VRR is only
--    parsed upstream in Linux 7.4 -- and on an MST branch the property is
--    not exposed at all.) vrr = 1 keeps it armed either way.
hl.monitor({
    output   = "desc:Dell Inc. DELL U3225QE 3Y4F584",
    mode     = "3840x2160@120",
    position = "0x0",
    scale    = 1.5,
    bitdepth = 10,
    cm       = "edid",
    vrr      = 1,
})

-- 2b. The second display: Dell SE2723DS, 27" 2K, native max 75 Hz.
--     It carries an AMD FreeSync VSDB (48-75 Hz), which is the block the
--     current kernel CAN parse -- so this panel gets real VRR, but only when
--     it sits on a DIRECT connector (the board's HDMI or DP). While it was
--     daisy-chained off the U3225QE's DP-out it was an MST branch, the
--     driver exposed no vrr_capable property there, and VRR stayed off.
--     On the board's HDMI it now reports vrr_capable = 1 and adaptive sync
--     is genuinely active (verified: the compositor's frame-callback
--     intervals vary between ~13 and ~40 ms instead of being pinned).
--     Keep it to the right of the 4K panel.
hl.monitor({
    output   = "desc:Dell Inc. DELL SE2723DS 5P097V3",
    mode     = "2560x1440@75",
    position = "2560x0",
    scale    = 1.0,
    vrr      = 1,
})

-- 3. GUI overrides. Absent file is not an error: a fresh machine has none.
--    hl.monitor() MERGES into the existing rule for the same output and the
--    last call wins per field, so this file owns scale/position/mode.
local override = configDir .. "/monitors.lua"
local chunk = loadfile(override)
if chunk then
    chunk()
end

-- 4. Re-arm VRR after the GUI override.
--    nwg-displays writes "vrr = 0/1" unconditionally, mirroring the kernel's
--    reported adaptive-sync state at the moment the GUI was used. That state
--    changes with the cabling, so the GUI's cached value goes stale: while
--    the SE2723DS was on an MST branch the GUI recorded vrr = 0, and it
--    would keep writing that even after the panel moved to the board's HDMI
--    and VRR became possible.
--    These rules touch ONLY vrr, so the GUI keeps full ownership of geometry.
--    Same desc: selectors, so they follow the panels across connectors.
hl.monitor({
    output = "desc:Dell Inc. DELL U3225QE 3Y4F584",
    vrr    = 1,
})

hl.monitor({
    output = "desc:Dell Inc. DELL SE2723DS 5P097V3",
    vrr    = 1,
})
